/** Small shared UI pieces. */

import { useEffect, useRef, useState, type ReactNode } from 'react';

import { renderAudiogram, serialize, type AudiogramData, type RenderOptions } from '../../audiogram';

export function YesNo({
  name,
  legend,
  value,
  onChange,
}: {
  readonly name: string;
  readonly legend: string;
  readonly value: boolean | null;
  readonly onChange: (v: boolean) => void;
}) {
  return (
    <fieldset>
      <legend>{legend}</legend>
      <div className="yesno">
        <label>
          <input type="radio" name={name} checked={value === true} onChange={() => onChange(true)} /> Yes
        </label>
        <label>
          <input type="radio" name={name} checked={value === false} onChange={() => onChange(false)} /> No
        </label>
      </div>
    </fieldset>
  );
}

/** Accessible modal confirmation (native <dialog>). */
export function ConfirmDialog({
  open,
  title,
  children,
  confirmLabel,
  onConfirm,
  onCancel,
}: {
  readonly open: boolean;
  readonly title: string;
  readonly children: ReactNode;
  readonly confirmLabel: string;
  readonly onConfirm: () => void;
  readonly onCancel: () => void;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal?.();
    if (!open && d.open) d.close?.();
  }, [open]);
  if (!open) return null;
  return (
    <dialog ref={ref} aria-labelledby="confirm-title" onCancel={(e) => (e.preventDefault(), onCancel())} open>
      <h2 id="confirm-title" style={{ marginTop: 0 }}>
        {title}
      </h2>
      {children}
      <div className="actions">
        <button type="button" className="danger" onClick={onConfirm}>
          {confirmLabel}
        </button>
        <button type="button" className="secondary" onClick={onCancel} autoFocus>
          Keep going
        </button>
      </div>
    </dialog>
  );
}

/** The §8 audiogram. The SVG is generated by our renderer (all text escaped). */
export function AudiogramView({ data, options }: { readonly data: AudiogramData; readonly options: RenderOptions }) {
  const svg = serialize(renderAudiogram(data, options));
  return <div className="audiogram-wrap" dangerouslySetInnerHTML={{ __html: svg }} />;
}

export function useTheme(): ['light' | 'dark', () => void] {
  const prefersDark = typeof matchMedia === 'function' && matchMedia('(prefers-color-scheme: dark)').matches;
  const [theme, setTheme] = useState<'light' | 'dark'>(() => {
    try {
      const saved = localStorage.getItem('aurohear.theme');
      if (saved === 'light' || saved === 'dark') return saved;
    } catch {
      /* storage blocked */
    }
    return prefersDark ? 'dark' : 'light';
  });
  useEffect(() => {
    document.documentElement.dataset['theme'] = theme;
    try {
      localStorage.setItem('aurohear.theme', theme);
    } catch {
      /* storage blocked */
    }
  }, [theme]);
  return [theme, () => setTheme((t) => (t === 'dark' ? 'light' : 'dark'))];
}

/** Seconds remaining until `untilMs` (performance.now() clock), ticking once a second. */
export function useCountdown(untilMs: number | null, now: () => number = () => performance.now()): number {
  const [left, setLeft] = useState(() => (untilMs === null ? 0 : Math.max(0, Math.ceil((untilMs - now()) / 1000))));
  useEffect(() => {
    if (untilMs === null) return;
    const tick = (): void => setLeft(Math.max(0, Math.ceil((untilMs - now()) / 1000)));
    tick();
    const id = setInterval(tick, 250);
    return () => clearInterval(id);
  }, [untilMs, now]);
  return left;
}
